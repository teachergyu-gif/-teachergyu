# 최종 수정(사용자 지정, 최종 번호 기준): 15·20·22·24·27·28·29번, 서답형 2, 표기 통일
def apply(Q, E):
    # 15번 <보기>: ⑤의 ‘제’가 보기에 있도록 ‘ᄆᆞ·ᄎᆞᆷ:내 제 ·ᄠᅳ·들 …’ 구절을 넣음
    b = Q['15']['bogi']
    old = '… ·내 ·이·ᄅᆞᆯ'
    assert old in b['text']
    b['text'] = b['text'].replace(old, '… ᄆᆞ·ᄎᆞᆷ:내 제 ·ᄠᅳ·들 시·러 펴·디 :몯ᄒᆞᇙ ·노·미 하·니·라 ·내 ·이·ᄅᆞᆯ')

    # 20번: ②·③ 자리 바꿈(정답 ② → ③)
    q, e = Q['20'], E['20']
    q['choices'][1], q['choices'][2] = q['choices'][2], q['choices'][1]
    assert q['choices'][2].startswith('‘ᄭᅮᆷ’')
    e['answer'] = '③'
    w = dict(e['wrong']); e['wrong'] = [['①', w['①']], ['②', w['③']], ['④', w['④']], ['⑤', w['⑤']]]

    # 22번: ‘적절한 것’으로 전환(정답 ③)
    Q['22']['stem'] = '<보기>의 ⓐ~ⓔ에 나타난 표기 방식에 대한 설명으로 적절한 것은?'
    Q['22']['choices'] = [
        'ⓐ의 ‘기픈’은 어간 ‘깊-’의 받침을 어미의 초성에 옮겨 적은 것으로, 소리 나는 대로 적되 형태소의 경계는 밝혀 적은 표기이다.',
        'ⓑ의 ‘곶’은 종성에 ‘ㅈ’을 그대로 적은 것으로, 15세기 문헌이 모두 종성부용초성의 원칙만을 따랐기 때문에 나타난 표기이다.',
        'ⓒ의 ‘몸이며’는 체언과 조사의 경계를 밝혀 적은 것으로, ⓐ와 달리 형태를 고정하여 적는 방식이 16세기에 나타났음을 보여 준다.',
        'ⓓ의 ‘님믈’은 ‘ㅁ’을 받침과 초성에 두 번 적은 것으로, 당시 ‘님’의 받침이 길게 발음되었음을 반영한 표기이다.',
        'ⓔ의 ‘깁퍼’는 받침에 ‘ㅂ’을, 초성에 ‘ㅍ’을 나누어 적었으므로, ⓓ와 달리 형태소의 경계를 밝힌 끊어 적기에 해당한다.']
    E['22'].update(answer='③',
        correct='‘몸이며’는 체언 ‘몸’과 조사 ‘이며’의 경계를 밝혀 적은 끊어 적기이다. 이어 적기 일색이던 15세기와 달리 16세기 『소학언해』에서 끊어 적기가 나타나기 시작한다.',
        wrong=[['①', '이어 적기는 소리 나는 대로 적는 표기로, 형태소의 경계를 밝히지 않는다. 경계를 밝혀 적는 것은 끊어 적기이다.'],
               ['②', '종성에 ‘ㅈ’을 그대로 적은 것은 『용비어천가』·『월인천강지곡』 등 일부 문헌의 예외이고, 15세기 대부분의 문헌은 8종성법을 따랐다.'],
               ['④', '거듭 적기는 이어 적기에서 끊어 적기로 넘어가는 과도기의 표기 습관이지, 받침이 길게 발음되었음을 반영한 것이 아니다.'],
               ['⑤', '‘깁퍼’는 ‘ㅍ’을 ‘ㅂ’과 ‘ㅍ’에 나누어 적은 거듭 적기로, 끊어 적기라면 ‘깊어’로 적었을 것이다.']])

    # 24번: ‘적절한 것’으로 전환(정답 ②)
    Q['24']['stem'] = '<보기>의 ⓐ~ⓔ에 쓰인 조사에 대한 설명으로 적절한 것은?'
    Q['24']['choices'] = [
        'ⓐ의 ‘ᄋᆡ’는 ‘사ᄉᆞᆷ’이 무정 명사이기 때문에 쓰인 관형격 조사로, 유정 명사였다면 ‘ㅅ’이 쓰였을 것이다.',
        'ⓑ의 ‘ᄋᆡ’는 ⓐ의 ‘ᄋᆡ’와 형태가 같지만, ‘밤에’로 풀이되는 처소의 부사격 조사로 쓰인 것이다.',
        'ⓒ의 ‘ㅅ’은 ‘부텨’가 모음으로 끝나는 체언이기 때문에 선택된 관형격 조사이다.',
        'ⓓ의 ‘에’는 ‘그릇’이 자음으로 끝나는 체언이기 때문에 선택된 것으로, 모음으로 끝났다면 ‘예’가 쓰였을 것이다.',
        'ⓔ의 ‘世尊ㅅ’과 ‘알ᄑᆡ’에는 모두 관형격 조사가 쓰여, ‘세존의 앞의’라는 뜻을 나타낸다.']
    E['24'].update(answer='②',
        correct='‘밤, 낮, 집, 앒’ 같은 일부 체언 뒤에서는 ‘ᄋᆡ/의’가 관형격이 아니라 처소의 부사격 조사로 쓰였다. ‘바ᄆᆡ’는 ‘밤에’이다.',
        wrong=[['①', '‘사ᄉᆞᆷ’은 유정 명사이므로 ‘ᄋᆡ’가 쓰였다. ‘ㅅ’은 무정 명사나 높임의 유정 명사 뒤에 쓰이므로 조건이 뒤바뀌었다.'],
               ['③', '‘부텨’ 뒤에 ‘ㅅ’이 쓰인 것은 높임의 대상이기 때문이지, 모음으로 끝났기 때문이 아니다.'],
               ['④', '‘에/애’는 자음·모음이 아니라 모음 조화에 따라 선택되며, ‘예’는 ‘ㅣ’나 반모음 ‘ㅣ’ 뒤에 쓰였다.'],
               ['⑤', '‘世尊ㅅ’의 ‘ㅅ’은 관형격이지만 ‘알ᄑᆡ(앒+ᄋᆡ)’의 ‘ᄋᆡ’는 처소의 부사격 조사로, ‘세존의 앞에’이다.']])

    # 27번: ‘적절한 것’으로 전환(정답 ⑤)
    Q['27']['stem'] = '<보기 1>을 바탕으로 <보기 2>의 ㉠~㉤을 분석한 내용으로 적절한 것은?'
    Q['27']['choices'] = [
        '㉠의 ‘죽다’는 형용사처럼 선어말 어미 없이 쓰였으므로 현재의 상태를 나타낸다.',
        '㉡의 ‘-ᄂᆞ-’는 동사와 형용사에 두루 쓰여 현재를 나타내는 선어말 어미이다.',
        '㉢의 ‘하다’에 ‘-더-’를 결합하면 ‘하더라’가 되어 앞으로의 상태를 나타낸다.',
        '㉣의 ‘닐오리라’에는 미래의 ‘-리-’와 함께, 주어가 2인칭임을 나타내는 ‘-오-’가 쓰였다.',
        '㉤의 ‘ᄒᆞ더이다’에는 과거를 나타내는 ‘-더-’와 청자를 높이는 ‘-이-’가 함께 쓰였다.']
    E['27'].update(answer='⑤',
        correct='‘-더-’는 과거를, ‘-이-’는 청자를 높이는 상대 높임 선어말 어미이다. 현대어 풀이 ‘맞이하고자 하더군요’에서 청자를 높이는 ‘-요’가 ‘-이-’에 해당한다.',
        wrong=[['①', '‘죽다’는 동사이므로 선어말 어미 없이 쓰이면 과거의 사건을 나타낸다. 형용사가 아니다.'],
               ['②', '‘-ᄂᆞ-’는 동사에만 결합하였고, 형용사는 선어말 어미 없이 현재를 나타냈다.'],
               ['③', '‘하더라’의 ‘-더-’는 과거를 나타내므로 ‘머리가 많았다’는 뜻이 된다. 미래는 ‘-리-’로 나타낸다.'],
               ['④', '‘-오-’는 주어가 1인칭임을 나타내는 선어말 어미로, 주어 ‘내’와 호응한다.']])

    # 28번 <보기>: ‘나ᇫ-(나아가다)+-오’ → ‘나ᅀᅩ’(15세기 ㅅ 불규칙 용언)
    b = Q['28']['bogi']
    assert 'ⓐ 거름 나소 ⓑ' in b['text']
    b['text'] = b['text'].replace('ⓐ 거름 나소 ⓑ', 'ⓐ 거름 나ᅀᅩ ⓑ')
    Q['28']['choices'][1] = Q['28']['choices'][1].replace('‘나소’', '‘나ᅀᅩ’')
    E['28']['wrong'] = [[k, t.replace('‘나소’', '‘나ᅀᅩ’')] for k, t in E['28']['wrong']]
    assert '나ᅀᅩ' in Q['28']['choices'][1]

    # 29번: ‘적절한 것’으로 전환(정답 ⑤)
    Q['29']['stem'] = Q['29']['stem'].replace('적절하지 <u>않은</u> 것은?', '적절한 것은?')
    assert Q['29']['stem'].endswith('적절한 것은?')
    Q['29']['choices'] = [
        '‘後世예’의 ‘예’는 ‘後世’가 한자어이기 때문에 쓰인 부사격 조사로, 고유어 뒤에서는 ‘에’만 쓰였다.',
        '‘홈이’와 ‘ᄆᆞᄎᆞᆷ이’는 모두 ‘ᄒᆞ-’, ‘ᄆᆞᆾ-’에 명사형 전성 어미가 결합한 뒤 조사가 붙은 것이다.',
        '‘몸을’, ‘道를’은 양성 모음 뒤에 음성 모음의 조사가 결합한 것으로, 15세기의 모음 조화 원칙이 그대로 유지되었음을 보여 준다.',
        '‘현뎌케’의 ‘뎌’에서 ‘ㄷ’이 유지된 것은 한자어이기 때문이며, 고유어에서는 16세기에 이미 ‘ㅈ’으로 바뀌어 있었다.',
        '‘베퍼ᄡᅥ’의 ‘ㅄ’은 서로 다른 글자를 나란히 쓴 합용 병서로, ‘ㅂ’이 발음되는 어두 자음군을 표기한 것으로 본다.']
    E['29'].update(answer='⑤',
        correct='‘ㅄ’은 ‘ㅂ’과 ‘ㅅ’을 나란히 쓴 합용 병서이며, ‘ㅂ’계 합용 병서는 각 자음이 발음되는 어두 자음군으로 보는 견해가 강하다.',
        wrong=[['①', '‘예’는 한자어·고유어와 관계없이 ‘ㅣ’나 반모음 ‘ㅣ’로 끝나는 체언 뒤에 쓰였다. ‘後世(후셰)’가 반모음 ‘ㅣ’로 끝나기 때문이다.'],
               ['②', '‘홈’은 ‘ᄒᆞ-+-옴’으로 명사형 전성 어미가 결합한 것이지만, ‘ᄆᆞᄎᆞᆷ’은 ‘ᄆᆞᆾ-+-ᄋᆞᆷ’으로 명사 파생 접사가 결합한 명사이다.'],
               ['③', '양성 모음 뒤에 ‘을, 를’이 온 것은 16세기에 모음 조화가 흔들렸음을 보여 주는 예이다.'],
               ['④', '구개음화는 한자어·고유어 모두 17~18세기 근대 국어 시기에 일어났으며, 16세기에는 둘 다 ‘ㄷ’이 유지되었다.']])

    # 서답형 2: 답란 번호를 1), 2)로(<조건> 1·2와 겹치지 않게)
    f = Q['서답형 2']
    assert f['form'].startswith('1. ㉠') and '\n2. ㉡' in f['form']
    f['form'] = f['form'].replace('1. ㉠', '1) ㉠', 1).replace('\n2. ㉡', '\n2) ㉡', 1)

    # 표기 통일: ‘좌표 평면상’(지문과 같게)
    for n in ('10', '11'):
        Q[n]['choices'][4] = Q[n]['choices'][4].replace('좌표 평면 상의', '좌표 평면상의')
        assert '평면상의' in Q[n]['choices'][4]

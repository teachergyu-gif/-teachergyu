def ctab(head, rows):
    C = 'style="text-align:center;padding:.5mm 5mm"'
    return ('<table class="ht chtab"><tr><td></td>' + ''.join(f'<td {C}>{h}</td>' for h in head) + '</tr>'
            + ''.join(f'<tr><td>{CIRC[i]}</td>' + ''.join(f'<td {C}>{w}</td>' for w in r) + '</tr>' for i, r in enumerate(rows)) + '</table>')


def two(a, b):
    """두 문장 선지: 괄호로 묶어 두 줄"""

def flow(steps, last):
    """분류 흐름도: steps = [(질문, 아니요 쪽 칸)], 마지막 ‘예’ 칸"""
    r = ''
    for k, (ask, no) in enumerate(steps):
        r += f'<tr><td><div class="fbox">{ask}</div></td><td class="ar">아니요 →</td><td><div class="fbox">{no}</div></td></tr>'
        r += '<tr><td class="dn">↓ 예</td><td></td><td></td></tr>'
    r += f'<tr><td><div class="fbox sm2">{last}</div></td><td></td><td></td></tr>'
    return f'<table class="flow">{r}</table>'


